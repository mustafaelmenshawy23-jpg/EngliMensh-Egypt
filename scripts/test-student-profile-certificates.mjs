import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';

const main = readFileSync(new URL('../src/main.js', import.meta.url), 'utf8');
const styles = readFileSync(new URL('../src/style.css', import.meta.url), 'utf8');
const packageJson = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));

assert.match(main, /STUDENT_PROFILES_KEY/);
assert.match(main, /englimensh_progress_.*state\.stage.*state\.grade.*state\.path/);
assert.match(main, /paths:\(form\.elements\.studentStage\.value === 'primary' \? \['general','advanced'\]/);
assert.match(main, /YOUR TWO PRIMARY CURRICULA/);
assert.match(main, /data-path=/);
assert.match(main, /attempted === questions\.length && score >= 90/);
assert.doesNotMatch(main, /certificate-teacher-photo/, 'teacher portrait is already embedded in certificate artwork');
assert.match(main, /certificate-student-photo/);
assert.equal(main.split('<h3>Certificate of Excellence</h3>').length - 1, 0, 'certificate title is already part of the artwork and must not be repeated');
assert.match(main, /data-student-hub/);
assert.match(main, /data-favorite-current/);
assert.match(main, /data-student-theme/);
assert.match(main, /value=\"ocean\"/);
assert.match(main, /value=\"forest\"/);
assert.match(main, /value=\"lavender\"/);
assert.match(main, /data-edit-student-profile/);
assert.match(main, /studentPhotoCamera/);
assert.match(main, /data-save-certificate/);
assert.match(main, /window\.print\(\)/);
assert.match(main, /const correctPosition = seed % 4/);
assert.match(styles, /data-student-theme=\"ocean\"/);
assert.match(styles, /data-student-theme=\"forest\"/);
assert.match(styles, /data-student-theme=\"lavender\"/);
assert.match(styles, /word-builder-slots,\.word-builder-tiles/);
assert.match(main, /data-student-hub/);
assert.match(styles, /\.certificate-card[^}]*certificate-template\.jpeg/);
assert.match(styles, /aspect-ratio:1189\/1600/, 'certificate must preserve the source artwork aspect ratio');
assert.doesNotMatch(styles, /\.certificate-teacher-photo/, 'do not overlay a duplicate teacher portrait');
assert.match(styles, /\.certificate-student-photo/);
assert.ok(existsSync(new URL('../public/assets/certificate-template.jpeg', import.meta.url)), 'certificate template asset is missing');
assert.ok(existsSync(new URL('../public/assets/teacher-portrait.jpeg', import.meta.url)), 'teacher portrait asset is missing');
assert.ok(packageJson.scripts.test.includes('test-student-profile-certificates.mjs'));
const curriculum = JSON.parse(readFileSync(new URL('../src/data/curriculum/structure.json', import.meta.url), 'utf8'));
const primary = curriculum.stages.find((stage) => stage.id === 'primary');
assert.deepEqual(primary.terms.map((term) => term.id), ['first', 'second']);
assert.equal(primary.terms.find((term) => term.id === 'second').visible, false, 'Second Term stays hidden until content is approved');
const index = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
assert.match(index, /startup-splash/);
assert.match(index, /EngliMensh/);
console.log('Student profiles, themes, certificate PDF, shuffled answers, Second Term preparation, and splash screen checks passed.');
